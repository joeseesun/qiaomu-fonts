"""Pen drawings for Trivulzio Quill, in proportions relative to x-height or cap height."""



def stroke(g, nodes, width=1):
    height = g.cap if g.case in {"uc", "fig"} else g.xh
    pen = g.P(width)
    for index, (x, y, direction, pressure) in enumerate(nodes):
        if index == 0:
            pen.m(x * height, y * height, direction, wm=pressure)
        elif direction is None:
            pen.l(x * height, y * height, wm=pressure)
        else:
            pen.c(x * height, y * height, direction, wm=pressure)
    g.add(pen)


